/**
 * @file tri_quadrature.h
 * @brief Triangle quadrature points and weights for prism elements.
 *
 * Provides the exact same triangle solution-point coordinates and quadrature
 * weights used by hpMusic (from scheme_coef_cpr_gsp_gfp_tri.C), plus the
 * pre-computed prolongation and restriction matrices for p-refinement on
 * triangles.
 *
 * For prism elements the full operator is: P_prism = P_1d ⊗ P_tri
 * where P_1d comes from gauss_quadrature.h (Gauss-Legendre 1D) and P_tri
 * comes from this file.
 *
 * All data is for the reference triangle with vertices (0,0), (1,0), (0,1).
 * Triangle SP count at order p: n_tri(p) = (p+1)(p+2)/2.
 *
 * Prism SP layout: index = i_zeta * n_tri + i_tri  (outer = 1D, inner = tri).
 * Prism SP count at order p: n_prism(p) = (p+1) * n_tri(p) = (p+1)^2*(p+2)/2.
 */

