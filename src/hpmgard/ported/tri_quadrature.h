/// Maximum triangle order supported (same as kMaxOrder in gauss_quadrature.h
/// but triangle R/P matrices are only available up to p=5).
static constexpr int kMaxTriOrder = 5;

/**
 * @brief Number of triangle solution points at order p.
 */
inline int NumSPTri(int p) { return (p + 1) * (p + 2) / 2; }

/**
 * @brief Number of prism solution points at order p.
 *        n_prism = n_1d * n_tri = (p+1) * (p+1)(p+2)/2
 */
inline int NumSPPrism(int p) { return (p + 1) * NumSPTri(p); }

