/**
 * @file gll_quadrature.h
 * @brief Gauss-Lobatto-Legendre (GLL) quadrature points and weights.
 *
 * Provides GLL nodes and weights for the reference interval [-1, 1],
 * used by Nek5000 and other Spectral Element Method (SEM) solvers.
 *
 * GLL nodes for n+1 points:
 *   - Always include endpoints -1 and +1
 *   - Interior points are roots of P'_n(xi) (derivative of Legendre polynomial)
 *
 * GLL weights:
 *   w_i = 2 / (n(n+1) [P_n(xi_i)]^2)
 *
 * Quadrature exactness: integrates polynomials of degree <= 2n-1 exactly
 * (compared to GL which integrates degree <= 2n+1 exactly).
 *
 * The diagonal mass matrix property still holds:
 *   M_{ij} = integral phi_i phi_j dx ≈ sum_k w_k phi_i(xi_k) phi_j(xi_k)
 *          = w_i delta_{ij}   (since phi_i(xi_k) = delta_{ik} for nodal basis)
 *
 * All data is for the reference interval [-1, 1].
 */

