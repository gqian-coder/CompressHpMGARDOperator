/**
 * @brief Number of 1D solution points at order p.
 */
inline int NumSP1D(int p) { return p + 1; }

/**
 * @brief Number of 2D (quad) solution points at order p.
 */
inline int NumSPQuad(int p) { return (p + 1) * (p + 1); }

/**
 * @brief Number of 3D (hex) solution points at order p.
 */
inline int NumSPHex(int p) { return (p + 1) * (p + 1) * (p + 1); }

